package com.fitness.ADT.aiservice.service;

import com.fitness.ADT.aiservice.model.Activity;
import com.fitness.ADT.aiservice.model.Recommendation;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;

import org.springframework.stereotype.Service;

import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.List;

@Service
@Slf4j
@RequiredArgsConstructor
public class ActivityAIService {

    /*
     * GeminiService communicates with the Gemini API.
     *
     * @RequiredArgsConstructor generates a constructor for this final field.
     * Spring automatically injects the GeminiService bean.
     */
    private final GeminiService geminiService;


    /*
     * MAIN METHOD
     *
     * This method coordinates the entire recommendation-generation process:
     *
     * 1. Create a prompt using the activity details.
     * 2. Send the prompt to Gemini.
     * 3. Process Gemini's response.
     * 4. Return a Recommendation object.
     *
     * ActivityMessageListener calls this method when Kafka delivers
     * an activity event to AI Service.
     */
    public Recommendation generateRecommendation(Activity activity) {

        // Create instructions for Gemini using the activity's information.
        String prompt = createPromptForActivity(activity);

        // Send the prompt to Gemini and receive its raw HTTP response.
        String aiResponse = geminiService.getRecommendations(prompt);

        // Log the response for debugging. Do not log API keys or secrets.
        log.info("Received response from Gemini for activity: {}", activity.getId());

        // Extract the generated recommendation and convert it into a Java object.
        return processAIResponse(activity, aiResponse);
    }


    /*
     * RESPONSE PROCESSING
     *
     * Gemini returns an API response containing the generated text.
     * That generated text should itself contain our requested recommendation JSON.
     *
     * We therefore need two parsing steps:
     *
     * 1. Parse the outer Gemini API response.
     * 2. Extract and parse the inner recommendation JSON.
     */
    private Recommendation processAIResponse(
            Activity activity,
            String aiResponse) {

        try {

            // ObjectMapper converts JSON strings into a navigable JSON tree.
            ObjectMapper mapper = new ObjectMapper();

            // STEP 1: Parse the complete response returned by Gemini.
            JsonNode rootNode = mapper.readTree(aiResponse);

            // If Gemini returns an API error, do not mistake it for a recommendation.
            if (rootNode.has("error")) {
                log.error("Gemini returned an API error: {}", rootNode.path("error"));
                return createDefaultRecommendation(activity);
            }

            // STEP 2: Extract the actual text generated by Gemini.
            String text = extractGeneratedText(rootNode);

            // Ensure we have generated text before attempting further parsing.
            if (text == null || text.isBlank()) {
                log.error("Gemini response did not contain generated text.");
                return createDefaultRecommendation(activity);
            }

            /*
             * Gemini may wrap its generated JSON in Markdown code fences.
             *
             * For example:
             * ```json
             * {"analysis": {...}}
             * ```
             *
             * Remove these fences before parsing the inner JSON.
             */
            String jsonContent = text
                    .replaceFirst("^\\s*```(?:json)?\\s*", "")
                    .replaceFirst("\\s*```\\s*$", "")
                    .trim();

            // STEP 3: Parse the JSON generated by the AI model.
            JsonNode analysisJson = mapper.readTree(jsonContent);

            // Extract the analysis section from the generated JSON.
            JsonNode analysisNode = analysisJson.path("analysis");

            /*
             * Combine the individual analysis fields into one readable string.
             * This string will be stored in Recommendation.recommendation.
             */
            StringBuilder fullAnalysis = new StringBuilder();

            addAnalysisSection( fullAnalysis, analysisNode, "overall", "Overall:");

            addAnalysisSection( fullAnalysis, analysisNode, "pace", "Pace:");

            addAnalysisSection( fullAnalysis, analysisNode, "heartRate", "Heart Rate:");

            addAnalysisSection( fullAnalysis, analysisNode, "caloriesBurned", "Calories Burned:");


            // Extract the lists from their respective JSON arrays.
            List<String> improvements = extractImprovements(analysisJson.path("improvements"));

            List<String> suggestions = extractSuggestions(analysisJson.path("suggestions"));

            List<String> safety = extractSafetyGuidelines(analysisJson.path("safety"));


            /*
             * STEP 4: Build the final Recommendation entity.
             *
             * The activity details come from the original Activity object.
             * The analysis, improvements, suggestions, and safety guidance
             * come from Gemini's generated JSON.
             *
             * The builder is generated by Lombok if Recommendation uses
             * @Builder.
             */
            return Recommendation.builder()
                    .activityId(activity.getId())
                    .userId(activity.getUserId())
                    .type(activity.getType().toString())
                    .recommendation(fullAnalysis.toString().trim())
                    .improvements(improvements)
                    .suggestions(suggestions)
                    .safety(safety)
                    .createdAt(LocalDateTime.now())
                    .build();

        } catch (Exception e) {

            /*
             * If the API response cannot be parsed, or its JSON does not
             * match the expected structure, log the problem and return
             * a fallback recommendation instead of losing the processing flow.
             */
            log.error(
                    "Failed to process AI response for activity: {}",
                    activity.getId(),
                    e
            );

            return createDefaultRecommendation(activity);
        }
    }


    /*
     * EXTRACT GENERATED TEXT FROM GEMINI
     *
     * Our Gemini Interactions API returns text inside:
     * steps -> model_output -> content -> text
     *
     * We also support the generateContent response format
     * used by the course instructor.
     */
    private String extractGeneratedText(JsonNode rootNode) {

        // FORMAT 1: Gemini Interactions API.
        JsonNode steps = rootNode.path("steps");

        if (steps.isArray()) {

            for (JsonNode step : steps) {

                // Ignore thought steps; we need the actual model output.
                if (!"model_output".equals(step.path("type").asText())) {
                    continue;
                }

                JsonNode content = step.path("content");

                if (content.isArray()) {

                    StringBuilder generatedText = new StringBuilder();

                    for (JsonNode item : content) {

                        // Extract only text items from the model output.
                        if ("text".equals(item.path("type").asText())) {

                            String text = item.path("text").asText("");

                            if (!text.isBlank()) {

                                if (!generatedText.isEmpty()) {
                                    generatedText.append("\n");
                                }

                                generatedText.append(text);
                            }
                        }
                    }

                    if (!generatedText.isEmpty()) {
                        return generatedText.toString();
                    }
                }
            }
        }

        // FORMAT 2: Gemini generateContent API.
        JsonNode candidates = rootNode.path("candidates");

        if (candidates.isArray() && !candidates.isEmpty()) {

            JsonNode parts = candidates
                    .get(0)
                    .path("content")
                    .path("parts");

            if (parts.isArray()) {

                StringBuilder generatedText = new StringBuilder();

                for (JsonNode part : parts) {

                    String text = part.path("text").asText("");

                    if (!text.isBlank()) {

                        if (!generatedText.isEmpty()) {
                            generatedText.append("\n");
                        }

                        generatedText.append(text);
                    }
                }

                if (!generatedText.isEmpty()) {
                    return generatedText.toString();
                }
            }
        }

        // No supported response structure contained generated text.
        return null;
    }




    /*
     * FALLBACK RECOMMENDATION
     *
     * Used when Gemini is unavailable or its response cannot be processed, helps produce a basic recommendation.
     *
     * Important: This is not an AI-generated analysis.
     */
    private Recommendation createDefaultRecommendation(Activity activity) {

        return Recommendation.builder()
                .activityId(activity.getId())
                .userId(activity.getUserId())
                .type(activity.getType().toString())
                .recommendation("Unable to generate detailed analysis")
                .improvements(
                        Collections.singletonList(
                                "Continue with your current routine"
                        )
                )
                .suggestions(
                        Collections.singletonList(
                                "Consider consulting a fitness professional"
                        )
                )
                .safety(
                        Arrays.asList(
                                "Follow appropriate safety guidelines"
                        )
                )
                .createdAt(LocalDateTime.now())
                .build();
    }


    /*
     * EXTRACT SAFETY GUIDELINES
     *
     * Expected JSON:
     *
     * "safety": [
     *     "Stay hydrated",
     *     "Stop if you experience pain"
     * ]
     *
     * Each array element becomes one String in the Java List.
     */
    private List<String> extractSafetyGuidelines(JsonNode safetyNode) {

        List<String> safety = new ArrayList<>();

        if (safetyNode.isArray()) {

            safetyNode.forEach(item ->
                    safety.add(item.asText())
            );
        }

        // Supply a default when the AI does not return safety guidelines.
        return safety.isEmpty()
                ? Collections.singletonList(
                "Follow general safety guidelines"
        )
                : safety;
    }


    /*
     * EXTRACT WORKOUT SUGGESTIONS
     *
     * Expected JSON:
     *
     * "suggestions": [
     *     {
     *         "workout": "Walking",
     *         "description": "Try a comfortable 20-minute walk"
     *     }
     * ]
     *
     * Each object becomes a readable String.
     */
    private List<String> extractSuggestions(JsonNode suggestionsNode) {

        List<String> suggestions = new ArrayList<>();

        if (suggestionsNode.isArray()) {

            suggestionsNode.forEach(suggestion -> {

                String workout =
                        suggestion.path("workout").asText("Workout");

                String description =
                        suggestion.path("description").asText("");

                suggestions.add(
                        String.format("%s: %s", workout, description)
                );
            });
        }

        return suggestions.isEmpty()
                ? Collections.singletonList(
                "No specific suggestions provided"
        )
                : suggestions;
    }


    /*
     * EXTRACT IMPROVEMENTS
     *
     * Expected JSON:
     *
     * "improvements": [
     *     {
     *         "area": "Endurance",
     *         "recommendation": "Increase duration gradually"
     *     }
     * ]
     *
     * Each improvement is converted into a readable String.
     */
    private List<String> extractImprovements(JsonNode improvementsNode) {

        List<String> improvements = new ArrayList<>();

        if (improvementsNode.isArray()) {

            improvementsNode.forEach(improvementNode -> {

                String area =
                        improvementNode.path("area").asText("General");

                String detail =
                        improvementNode.path("recommendation").asText("");

                improvements.add(
                        String.format("%s: %s", area, detail)
                );
            });
        }

        return improvements.isEmpty()
                ? Collections.singletonList(
                "No specific improvements provided"
        )
                : improvements;
    }


    /*
     * ADD AN ANALYSIS SECTION
     *
     * Reads a particular field from the analysis JSON and appends it
     * to the combined analysis StringBuilder.
     *
     * Example:
     * key = "pace"
     * prefix = "Pace:"
     */
    private void addAnalysisSection(
            StringBuilder fullAnalysis,
            JsonNode analysisNode,
            String key,
            String prefix) {

        JsonNode value = analysisNode.path(key);

        // Ignore missing, null, or empty analysis fields.
        if (!value.isMissingNode()
                && !value.isNull()
                && !value.asText("").isBlank()) {

            fullAnalysis.append(prefix)
                    .append(" ")
                    .append(value.asText())
                    .append("\n\n");
        }
    }


    /*
     * CREATE THE GEMINI PROMPT
     *
     * Provides Gemini with:
     * - The required JSON structure.
     * - The activity's type, duration, and calories.
     * - Additional activity metrics.
     *
     * The explicit JSON schema helps the next method parse the response
     * consistently.
     */
    private String createPromptForActivity(Activity activity) {

        return String.format(
                """
                Analyze this fitness activity and provide detailed recommendations.

                Return ONLY valid JSON. Do not include Markdown code fences,
                introductory text, or explanations outside the JSON object.

                Use this exact JSON structure:

                {
                  "analysis": {
                    "overall": "Overall analysis here",
                    "pace": "Pace analysis here",
                    "heartRate": "Heart rate analysis here",
                    "caloriesBurned": "Calories analysis here"
                  },
                  "improvements": [
                    {
                      "area": "Area name",
                      "recommendation": "Detailed recommendation"
                    }
                  ],
                  "suggestions": [
                    {
                      "workout": "Workout name",
                      "description": "Detailed workout description"
                    }
                  ],
                  "safety": [
                    "Safety point 1",
                    "Safety point 2"
                  ]
                }

                Analyze this activity:

                Activity Type: %s
                Duration: %d minutes
                Calories Burned: %d
                Additional Metrics: %s

                Provide useful recommendations focused on performance,
                improvements, suitable future workouts, and safety.

                Do not invent measurements that are not supplied.
                If a metric is unavailable, state that it was not provided.
                """,
                activity.getType(),
                activity.getDuration(),
                activity.getCaloriesBurned(),
                activity.getAdditionalMetrics()
        );
    }
}